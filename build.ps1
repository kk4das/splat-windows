<#
.SYNOPSIS
  Builds SPLAT! and its utilities for Windows with MSYS2 UCRT64 GCC. Replaces upstream's bash
  `configure` + `build` + `utils/build`.

.DESCRIPTION
  - Like `configure`, it writes a splat.h per mode (#define HD_MODE / MAXPAGES), here under
    build\gen-std and build\gen-hd rather than into src\ (src\ stays the source tree only).
  - Same compiler flags as upstream `build` and `utils/build`, except:
      * -mcmodel=medium is dropped (it doesn't exist for Windows targets; see runbook P2), and
      * -static is added, so the .exe files need no MSYS2 DLLs (Stage 0 proved this).
  - srtm2sdf-hd.exe is a COPY of srtm2sdf.exe (upstream uses a symlink; srtm2sdf picks HD mode
    from its own program name, so a copy works and needs no admin rights; runbook P6).
  - Output goes to dist\ (git-ignored). Compiler messages go to build\logs\.

.PARAMETER StdPages  MAXPAGES for standard (3") mode: 4,9,16,25,36,49,64 = 2x2 ... 8x8 degrees.
.PARAMETER HdPages   MAXPAGES for HD (1") mode: 1,4,9,16,25,36,49,64 = 1x1 ... 8x8 degrees, or 0 for no HD build.
#>
param(
    [ValidateSet(4,9,16,25,36,49,64)] [int]$StdPages = 64,    # owner D5: 8x8
    [ValidateSet(0,1,4,9,16,25,36,49,64)] [int]$HdPages = 16, # owner D5: 4x4
    [string]$Msys = 'C:\msys64',
    [string]$Out = (Join-Path $PSScriptRoot 'dist')
)
$ErrorActionPreference = 'Stop'
$Root = $PSScriptRoot
$Src  = Join-Path $Root 'src'
$Bin  = Join-Path $Msys 'ucrt64\bin'
$Gpp  = Join-Path $Bin 'g++.exe'
$Gcc  = Join-Path $Bin 'gcc.exe'
$Logs = Join-Path $Root 'build\logs'
foreach ($t in $Gpp, $Gcc) { if (-not (Test-Path $t)) { throw "compiler not found: $t (run scripts\verify_toolchain.ps1)" } }
New-Item -ItemType Directory -Force $Out, $Logs | Out-Null

# Upstream src/build:       g++ -O2 -s -fomit-frame-pointer -ffast-math -pipe -march=$cpu $model ... -lm -lbz2
# Upstream src/utils/build: cc  -O2 -s -fomit-frame-pointer ...
$SplatFlags = @('-O2','-s','-fomit-frame-pointer','-ffast-math','-pipe','-march=x86-64','-static')
$UtilFlags  = @('-O2','-s','-fomit-frame-pointer','-static')

function Invoke-Compile([string]$cc, [string[]]$argList, [string]$name) {
    $log = Join-Path $Logs "$name.log"
    $env:PATH = "$Bin;$env:PATH"   # cc1/as/ld live next to gcc; process-local only
    $p = Start-Process -FilePath $cc -ArgumentList $argList -NoNewWindow -Wait -PassThru `
         -RedirectStandardError $log -RedirectStandardOutput "$log.out"
    $warn = @(Select-String -Path $log -Pattern 'warning:' -ErrorAction SilentlyContinue).Count
    $err  = @(Select-String -Path $log -Pattern 'error' -ErrorAction SilentlyContinue).Count
    $exe  = Join-Path $Out "$name.exe"
    if ($p.ExitCode -eq 0 -and (Test-Path $exe)) {
        Write-Host ("{0,-14} OK    {1,7:N0} KB  warnings={2}" -f $name, ((Get-Item $exe).Length/1KB), $warn)
        return $true
    }
    Write-Host ("{0,-14} FAIL  exit={1} warnings={2} errors={3}  (see build\logs\{0}.log)" -f $name, $p.ExitCode, $warn, $err)
    Get-Content $log | Select-String 'error' | Select-Object -First 6 | ForEach-Object { Write-Host ("    " + $_.Line.Trim()) }
    return $false
}

function New-ParmsHeader([string]$dir, [int]$hd, [int]$pages) {
    New-Item -ItemType Directory -Force $dir | Out-Null
    $h = "/*`n  Parameters for $(if($hd){'1 arc-second high'}else{'3 arc-second standard'}) resolution mode of operation`n  Generated by build.ps1 on $(Get-Date -Format s)`n*/`n#define HD_MODE $hd`n#define MAXPAGES $pages`n"
    [IO.File]::WriteAllText((Join-Path $dir 'splat.h'), $h)
}

$ok = $true
Write-Output "SPLAT! Windows build: standard MAXPAGES=$StdPages, HD MAXPAGES=$HdPages -> $Out"
New-ParmsHeader (Join-Path $Root 'build\gen-std') 0 $StdPages
Remove-Item (Join-Path $Out 'splat.exe') -ErrorAction SilentlyContinue
$ok = (Invoke-Compile $Gpp ($SplatFlags + @('-I', (Join-Path $Root 'build\gen-std'), "$Src\itwom3.0.cpp", "$Src\splat.cpp", '-lm', '-lbz2', '-o', (Join-Path $Out 'splat.exe'))) 'splat')[-1] -and $ok
if ($HdPages -gt 0) {
    New-ParmsHeader (Join-Path $Root 'build\gen-hd') 1 $HdPages
    Remove-Item (Join-Path $Out 'splat-hd.exe') -ErrorAction SilentlyContinue
    $ok = (Invoke-Compile $Gpp ($SplatFlags + @('-I', (Join-Path $Root 'build\gen-hd'), "$Src\itwom3.0.cpp", "$Src\splat.cpp", '-lm', '-lbz2', '-o', (Join-Path $Out 'splat-hd.exe'))) 'splat-hd')[-1] -and $ok
}
$utils = [ordered]@{ citydecoder = @(); usgs2sdf = @(); srtm2sdf = @('-lbz2'); fontdata = @('-lz'); bearing = @('-lm') }
foreach ($u in $utils.Keys) {
    Remove-Item (Join-Path $Out "$u.exe") -ErrorAction SilentlyContinue
    $ok = (Invoke-Compile $Gcc ($UtilFlags + @("$Src\utils\$u.c") + $utils[$u] + @('-o', (Join-Path $Out "$u.exe"))) $u)[-1] -and $ok
}
if (Test-Path (Join-Path $Out 'srtm2sdf.exe')) {
    Copy-Item (Join-Path $Out 'srtm2sdf.exe') (Join-Path $Out 'srtm2sdf-hd.exe') -Force
    Write-Output ("{0,-14} OK    copy of srtm2sdf.exe (HD mode is chosen from the program name)" -f 'srtm2sdf-hd')
}
Write-Output ("BUILD: " + $(if ($ok) { 'OK' } else { 'FAILED' }))
exit $(if ($ok) { 0 } else { 1 })
